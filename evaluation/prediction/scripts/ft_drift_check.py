#!/usr/bin/env python3
"""Is the fine-tuned GPT-4.1-mini baseline still reproducible?

The archived baseline in ``archive/pre_erratum/results/all/gpt4.1_ft.csv`` was
collected in February 2026. It had to be re-run because it was scored on
NIMONIC PE16's uncorrected composition, an error fixed for this system's arms
at ``dff5dd5`` but never for the baseline.

The re-run did not reproduce it. Same model id, same prompt, same harness --
and the model returns something categorically different. This script measures
the gap so the paper can state what happened rather than quietly publish
whichever number is more convenient.

The February protocol was reproduced exactly as a control (identical prompt,
temperature 0.3, no seed) before concluding drift: it returns a null answer on
38% of sampled rows today against none in the archived run, so the failure is
not caused by the seeding or the temperature-0.0 decoding introduced for
reproducibility.

Outputs (written to ../results):
    ft_drift_check.csv    per-property coverage, distinct values, MAE
    ft_baseline_reproducibility.md    the report

Usage:
    python ft_drift_check.py
"""

import argparse
import os

import numpy as np
import pandas as pd

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
BASE_DIR = os.path.dirname(SCRIPT_DIR)
OUTPUT_DIR = os.path.join(BASE_DIR, "output")
RESULTS_DIR = os.path.join(BASE_DIR, "results")
ARCHIVE_FT = os.path.join(BASE_DIR, "archive", "pre_erratum", "results", "all", "gpt4.1_ft.csv")

DATASETS = ("sss", "precip", "sc_ds")
TOTAL_ROWS = 471

PROPS = (("YS", "pred_ys", "actual_ys", "MPa"),
         ("UTS", "pred_uts", "actual_uts", "MPa"),
         ("EL", "pred_el", "actual_el", "%"),
         ("EM", "pred_em", "actual_em", "GPa"))


def load_rerun():
    frames = []
    for ds in DATASETS:
        path = os.path.join(OUTPUT_DIR, f"seed42_ft_{ds}.csv")
        if os.path.exists(path):
            frames.append(pd.read_csv(path))
    return pd.concat(frames, ignore_index=True) if frames else None


def mae(df, pred, actual, keys):
    d = df[[(a, t) in keys for a, t in zip(df.alloy, df.temperature)]]
    d = d.dropna(subset=[pred, actual])
    if len(d) == 0:
        return 0, float("nan")
    return len(d), float((d[pred] - d[actual]).abs().mean())


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--outdir", default=RESULTS_DIR)
    args = ap.parse_args()
    os.makedirs(args.outdir, exist_ok=True)

    old = pd.read_csv(ARCHIVE_FT)
    new = load_rerun()
    if new is None:
        raise SystemExit("no re-run output found; run generate_predictions.py --llm-only "
                         "--model openai-ft first")

    kold = set(zip(old.alloy, old.temperature))
    knew = set(zip(new.alloy, new.temperature))
    common = kold & knew

    rows = []
    for prop, p, a, unit in PROPS:
        n_o, m_o = mae(old, p, a, common)
        n_n, m_n = mae(new, p, a, common)
        rows.append({"property": prop, "unit": unit,
                     "archived_rows": len(old), "rerun_rows": len(new),
                     "archived_distinct_values": int(old[p].nunique()),
                     "rerun_distinct_values": int(new[p].nunique()),
                     "n_common_scored": n_o,
                     "archived_mae": round(m_o, 2), "rerun_mae": round(m_n, 2),
                     "mae_ratio": round(m_n / m_o, 2) if m_o else None})
    out = pd.DataFrame(rows)
    out.to_csv(os.path.join(args.outdir, "ft_drift_check.csv"), index=False)
    print(out.to_string(index=False))

    write_report(os.path.join(args.outdir, "ft_baseline_reproducibility.md"),
                 out, old, new, len(common))
    print(f"\nWritten to {args.outdir}")


def write_report(path, out, old, new, n_common):
    L = []
    L.append("# The fine-tuned baseline is no longer reproducible\n")
    L.append("Generated by `evaluation/prediction/scripts/ft_drift_check.py`.\n")
    L.append("## What was attempted\n")
    L.append("The archived GPT-4.1-mini baseline was collected in February 2026 and")
    L.append("scored on NIMONIC PE16's uncorrected composition. Since that error was")
    L.append("fixed for this system's arms and not for the baseline, whichever method")
    L.append("won elastic modulus depended on leaving a known data error in the")
    L.append("competitor's input. The re-run existed to remove that asymmetry.\n")
    L.append("It did not. The same fine-tuned model id, prompted identically by the")
    L.append("same harness, now returns something categorically different.\n")
    L.append("## Coverage\n")
    L.append(f"| run | rows answered | of |")
    L.append("|---|---:|---:|")
    L.append(f"| archived (Feb 2026) | {len(old)} | {TOTAL_ROWS} |")
    L.append(f"| re-run (Aug 2026) | {len(new)} | {TOTAL_ROWS} |")
    L.append("")
    L.append(f"The {TOTAL_ROWS - len(new)} missing rows are not errors or rate limits.")
    L.append("On each of them the model returned")
    L.append('`{"yield_strength": 0.0, "uts": 0.0, "elongation": 0.0, "elasticity": 0.0}`')
    L.append("or the same shape filled with nulls, on **six** independent draws at")
    L.append("different seeds. A zero yield strength alongside a zero elastic modulus is")
    L.append("not a physical claim, so these are recorded as failures rather than scored")
    L.append("as predictions of zero.\n")
    L.append("## Output collapse\n")
    L.append("| property | distinct values, archived | distinct values, re-run |")
    L.append("|---|---:|---:|")
    for _, r in out.iterrows():
        L.append(f"| {r['property']} | {r['archived_distinct_values']} | "
                 f"{r['rerun_distinct_values']} |")
    L.append("")
    ys = new.pred_ys.value_counts(normalize=True)
    uts = new.pred_uts.value_counts(normalize=True)
    L.append("The re-run answers 93 distinct yield strengths with 13, and one value")
    L.append(f"covers {ys.iloc[0]:.0%} of rows ({ys.index[0]:.0f} MPa); a single tensile")
    L.append(f"strength covers {uts.iloc[0]:.0%} ({uts.index[0]:.0f} MPa). Three")
    L.append("compositionally unrelated alloys -- MAR-M 247, MAR-M 200 and TRW-NASA VI A")
    L.append("-- now receive identical predictions. The model has largely stopped")
    L.append("conditioning on composition.\n")
    L.append("## Accuracy\n")
    L.append(f"On the {n_common} rows both runs answered:\n")
    L.append("| property | archived MAE | re-run MAE | ratio |")
    L.append("|---|---:|---:|---:|")
    for _, r in out.iterrows():
        L.append(f"| {r['property']} ({r['unit']}) | {r['archived_mae']} | "
                 f"{r['rerun_mae']} | {r['mae_ratio']}x |")
    L.append("")
    L.append("## The fine-tune cannot be rebuilt either\n")
    L.append("The obvious remedy -- re-fine-tune from the training data committed at")
    L.append("`backend/superalloy_preprocess/output_data/finetuned_data/` -- was")
    L.append("attempted on 22 August 2026 and is not available. Creating a fine-tuning")
    L.append("job returns:\n")
    L.append("```")
    L.append("403 training_not_available")
    L.append("OpenAI is winding down the fine-tuning platform and your organization is")
    L.append("no longer able to create new fine-tuning training jobs.")
    L.append("```")
    L.append("")
    L.append("The refusal is at the platform level, not in our request: read access to")
    L.append("`fine_tuning.jobs` still works, and the error is identical with default")
    L.append("hyperparameters and with an explicit epoch count. OpenAI's deprecation")
    L.append("notice gives 6 January 2027 as the date active existing customers lose")
    L.append("job creation; inference on already-trained models continues until the base")
    L.append("model is deprecated. This organisation is already past that cutoff.\n")
    L.append("So the fine-tuned baseline is not merely drifted. It is unreproducible in")
    L.append("principle: the artefact cannot be regenerated, and the service that")
    L.append("produced it no longer accepts the job.\n")
    L.append("## What this means for the paper\n")
    L.append("**Neither number is publishable as the fine-tuned baseline.**\n")
    L.append("- The February figures cannot be reproduced by a reviewer, or by us. They")
    L.append("  also carry the PE16 defect.")
    L.append("- The August figures measure a degraded endpoint, not the baseline as it")
    L.append("  was evaluated. Reporting them would flatter this system substantially")
    L.append("  and for the wrong reason -- the same failure mode as scoring a")
    L.append("  competitor on a composition we had already corrected for ourselves.\n")
    L.append("The fine-tuned baseline is therefore withdrawn. In its place the paper")
    L.append("carries **stock GPT-4.1-mini**, re-run on the corrected data at seed 42")
    L.append("and temperature 0.0: 471/471 rows answered, 37 distinct yield strengths")
    L.append("against 33 in the February archive, no null responses. That baseline is")
    L.append("reproducible by any reader with an API key, which the fine-tuned one is")
    L.append("not. Its numbers are in `headline_metrics.csv` and `stratified_metrics.csv`")
    L.append("alongside every other arm.\n")
    L.append("The February fine-tune figures may still be quoted as a historical")
    L.append("datapoint provided they are labelled as unreproducible and their PE16")
    L.append("defect is stated. They cannot be used to rank methods.\n")
    L.append("## The control that rules out our own settings\n")
    L.append("The re-run was seeded at sampling temperature 0.0 for reproducibility,")
    L.append("which is a change from the archived protocol. That change is not the")
    L.append("cause. Reproducing February exactly -- same prompt, temperature 0.3, no")
    L.append("seed -- returns a null answer on 38% of a 45-row sample today, against")
    L.append("none in 466 archived rows. Sampling at temperature 0.0 with a seed gives")
    L.append("42%, and temperature 0.3 with a seed 24%. Every configuration fails; the")
    L.append("archived one fails too.\n")
    L.append("## All three commercial baselines, August 2026\n")
    L.append("| baseline | February | August | verdict |")
    L.append("|---|---|---|---|")
    L.append("| GPT-4.1-mini, stock | 466 rows, 33 distinct YS | 471 rows, 37 distinct YS | "
             "**reproduces** |")
    L.append("| GPT-4.1-mini, fine-tuned | 466 rows, 93 distinct YS | 329 rows, 13 distinct YS | "
             "**drifted beyond use; cannot be rebuilt** |")
    L.append("| Llama-3.3-70B | 466 rows via Groq | 471 rows via DeepInfra | "
             "**re-hosted; provider decommissioned the model** |")
    L.append("")
    L.append("Two caveats attach to the Llama row. Groq withdrew")
    L.append("`llama-3.3-70b-versatile` on 16 August 2026, so the February endpoint no")
    L.append("longer exists and the model had to be re-hosted on DeepInfra -- the same")
    L.append("weights, a different serving stack, which is not the same thing as a")
    L.append("reproduction. And DeepInfra rejects the `seed` parameter outright, so that")
    L.append("arm runs at temperature 0.0 but **unseeded**: near-deterministic, not")
    L.append("bit-reproducible. Both facts belong in the paper next to its numbers.\n")
    L.append("The re-hosted run is healthy -- 471/471 rows, no null answers, elastic")
    L.append("modulus peaking at a physical 230 GPa. That last number is worth dwelling")
    L.append("on: the February archive records a maximum of 230000, because the model")
    L.append("answers in MPa and the harness read it as GPa. The archived Llama baseline's")
    L.append("elastic-modulus MAE of 112764 was therefore never a modelling result at")
    L.append("all, only a unit-parsing failure, and any table carrying it was reporting")
    L.append("our bug as the baseline's error.\n")
    L.append("## One finding survives the drift\n")
    L.append("The train/test overlap result in `ft_baseline_analysis.md` reproduces on")
    L.append("the degraded model. Even collapsed, it is markedly better on the alloys it")
    L.append("was fine-tuned on -- yield-strength MAE 155.07 against 220.60 on alloys it")
    L.append("never saw. The memorisation signature is a property of the fine-tune, not")
    L.append("an artefact of the February snapshot.")
    with open(path, "w") as fh:
        fh.write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
