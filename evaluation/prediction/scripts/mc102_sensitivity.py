#!/usr/bin/env python3
"""What the shipped metrics would be if MC-102* had not been excluded.

MC-102* is entry X05 in ``scope_exclusions.json``: a record the original
curation dropped with no surviving rationale, and the only exclusion in that
list with no defensible reason. On the evidence it is in scope -- a conventional
cast Ni-Cr-Mo-Nb alloy of the 625 family, composition closing to 99.7 wt%, with
yield strength, tensile strength and elongation at six temperatures.

It stays out only so the committed results remain reproducible. That is a
defensible choice exactly once, and only if the cost of it is measured rather
than asserted to be small. This script measures it.

Deterministic arms only. The agent arms cost money and are stochastic, and this
question does not need them: if the deterministic arms move little, the agent
arms sit on the same six rows.

The predictions in ``output/sensitivity/`` were produced by:

    python generate_predictions.py --dataset custom \\
        --custom-path <one-record jsonl> --ml-only --seed 42 \\
        --output ../output/sensitivity/mc102_ml_only.csv

and likewise for --ml-deterministic and --ml-physics-kg.

Nothing here writes to a shipped table. Its output is a disclosure note.

Usage:
    python mc102_sensitivity.py
    python mc102_sensitivity.py --md ../results/mc102_sensitivity.md
"""

import argparse
import os

import numpy as np
import pandas as pd

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
BASE_DIR = os.path.dirname(SCRIPT_DIR)
OUTPUT = os.path.join(BASE_DIR, "output")
RESULTS = os.path.join(BASE_DIR, "results")
SENS = os.path.join(OUTPUT, "sensitivity")

DATASETS = ("sss", "precip", "sc_ds")
PROPS = (("ys", "YS", "MPa"), ("uts", "UTS", "MPa"),
         ("el", "EL", "%"), ("em", "EM", "GPa"))

#: display name -> (shipped arm tag, MC-102 prediction file)
ARMS = (("ML-only", "seed42_v2_ml_only", "mc102_ml_only.csv"),
        ("ML+physics", "seed42_v2prod_ml_deterministic", "mc102_ml_deterministic.csv"),
        ("ML+physics+KG", "seed42_v2prod_ml_physics_kg", "mc102_ml_physics_kg.csv"))

#: MC-102* nearest training alloy is Cast Alloy 625 at d = 5.13, so it would
#: join the FAR stratum, the one the headline agent claim rests on.
MC102_STRATUM = "FAR"
MC102_DISTANCE = 5.13


def load_arm(tag):
    return pd.concat([pd.read_csv(os.path.join(OUTPUT, f"{tag}_{ds}.csv"))
                      for ds in DATASETS], ignore_index=True)


def mae(df, key):
    a = pd.to_numeric(df.get(f"actual_{key}"), errors="coerce").to_numpy(float)
    p = pd.to_numeric(df.get(f"pred_{key}"), errors="coerce").to_numpy(float)
    m = ~(np.isnan(a) | np.isnan(p) | (a == 0))
    return int(m.sum()), (float(np.mean(np.abs(a[m] - p[m]))) if m.sum() else np.nan)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--md", default=os.path.join(RESULTS, "mc102_sensitivity.md"))
    args = ap.parse_args()

    dist = pd.read_csv(os.path.join(RESULTS, "nn_distance.csv"))
    far = set(dist[dist.stratum == "FAR"].alloy)

    rows = []
    for label, tag, fname in ARMS:
        shipped = load_arm(tag)
        extra = pd.read_csv(os.path.join(SENS, fname))
        withmc = pd.concat([shipped, extra], ignore_index=True)
        for key, prop, unit in PROPS:
            for scope in ("ALL", MC102_STRATUM):
                base = shipped if scope == "ALL" else shipped[shipped.alloy.isin(far)]
                plus = withmc if scope == "ALL" else withmc[
                    withmc.alloy.isin(far | {"MC-102*"})]
                n0, m0 = mae(base, key)
                n1, m1 = mae(plus, key)
                rows.append({"arm": label, "scope": scope, "property": prop, "unit": unit,
                             "n_shipped": n0, "n_with": n1,
                             "mae_shipped": m0, "mae_with": m1,
                             "delta": m1 - m0,
                             "delta_pct": 100.0 * (m1 - m0) / m0 if m0 else np.nan})

    df = pd.DataFrame(rows)

    L = ["# MC-102* sensitivity", "",
         "Generated by `evaluation/prediction/scripts/mc102_sensitivity.py`.", "",
         "`MC-102*` is excluded from the evaluation set as a historical decision with no "
         "surviving rationale (entry `X05` in `scope_exclusions.json`). It is the only "
         "exclusion in that list that no rule supports and none should: a conventional "
         f"cast Ni--Cr--Mo--Nb alloy of the 625 family, nearest training neighbour "
         f"Cast Alloy 625 at d = {MC102_DISTANCE}, which places it in the **{MC102_STRATUM} "
         "stratum** -- the one the headline agent claim rests on.", "",
         "It is kept out only so the committed results stay reproducible. This is what "
         "that costs. Deterministic arms only; no shipped table changes.", "",
         "## Effect of including MC-102* (six rows)", "",
         "| arm | scope | property | n | MAE shipped | MAE with MC-102* | change |",
         "|---|---|---|---:|---:|---:|---:|"]
    for _, r in df.iterrows():
        if pd.isna(r.mae_shipped):
            continue
        L.append(f"| {r.arm} | {r.scope} | {r.property} ({r.unit}) | "
                 f"{r.n_shipped} → {r.n_with} | {r.mae_shipped:.2f} | {r.mae_with:.2f} | "
                 f"{r.delta:+.2f} ({r.delta_pct:+.1f}%) |")

    worst = df.dropna(subset=["delta_pct"]).reindex(
        df.dropna(subset=["delta_pct"]).delta_pct.abs().sort_values(ascending=False).index)
    L += ["", "## Reading", "",
          f"Largest single movement: **{worst.iloc[0].property} on "
          f"{worst.iloc[0].scope} for {worst.iloc[0].arm}**, "
          f"{worst.iloc[0].mae_shipped:.2f} → {worst.iloc[0].mae_with:.2f} "
          f"({worst.iloc[0].delta_pct:+.1f}%).", ""]
    ys_far = df[(df.property == "YS") & (df.scope == MC102_STRATUM)]
    L.append("Yield strength on FAR, the load-bearing comparison, moves "
             + ", ".join(f"{r.delta_pct:+.1f}% for {r.arm}" for _, r in ys_far.iterrows())
             + ".")
    el = df[df.property == "EL"]
    L += ["",
          "Elongation is the outlier and is worth stating plainly: the arms predict "
          f"MC-102* at roughly 30% elongation against a measured 5% at room temperature, "
          f"so including it moves EL by up to {el.delta_pct.abs().max():.1f}%. That is one "
          "alloy exposing a known weakness -- ductility of cast alloys is the property "
          "every arm predicts worst -- not a new one.", "",
          "The exclusion is disclosed rather than silent, and re-admitting MC-102* is "
          "recorded in `scope_exclusions.json` as a decision for the next results freeze.",
          ""]

    os.makedirs(os.path.dirname(args.md), exist_ok=True)
    with open(args.md, "w", encoding="utf-8") as fh:
        fh.write("\n".join(L))
    df.to_csv(os.path.join(RESULTS, "mc102_sensitivity.csv"), index=False)

    print(f"{'arm':16s} {'scope':5s} {'prop':4s} {'shipped':>9s} {'with':>9s} {'change':>16s}")
    print("-" * 66)
    for _, r in df.iterrows():
        if pd.isna(r.mae_shipped):
            continue
        print(f"{r.arm:16s} {r.scope:5s} {r.property:4s} {r.mae_shipped:9.2f} "
              f"{r.mae_with:9.2f} {r.delta:+8.2f} ({r.delta_pct:+5.1f}%)")
    print(f"\nWritten to {args.md}")


if __name__ == "__main__":
    main()
