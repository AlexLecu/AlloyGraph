#!/usr/bin/env python3
"""LaTeX tables for the manuscript, generated from the committed results.

Every number is read from a results CSV or JSON in the repository; nothing is
recomputed and nothing is typed by hand, so a table cannot drift from the data
that produced it. Tables use booktabs and carry no vertical rules.

Emits, into ../../paper_assets/tables:
    T1_main.tex        headline comparison, all arms, MAE and R2 per property
    T2_stratified.tex  per-stratum MAE for the four internal arms
    T3_provenance.tex  mechanism, where it helps, and the supporting evidence
    T4_design.tex      inverse-design arms and their three success criteria
    T5_conformal.tex   conformal coverage and interval width per stratum

Usage:
    python make_tables.py
    python make_tables.py --outdir /tmp
"""

import argparse
import json
import os

import pandas as pd

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(os.path.dirname(SCRIPT_DIR))
RESULTS = os.path.join(PROJECT_ROOT, "evaluation", "prediction", "results")
DESIGN = os.path.join(PROJECT_ROOT, "evaluation", "design", "results")
DEFAULT_OUT = os.path.join(PROJECT_ROOT, "paper_assets", "tables")

PROPS = (("YS", "MPa"), ("UTS", "MPa"), ("EL", r"\%"), ("EM", "GPa"))

#: Display name -> key in headline_metrics.csv. Order is the paper's order:
#: our ablation ladder, then commercial LLM baselines, then method baselines.
T1_ARMS = [
    ("ML-only", "ML-only", "internal"),
    ("ML + physics", "ML+physics", "internal"),
    ("ML + physics + KG", "ML+physics+KG", "internal"),
    ("Full system (5 seeds)", "Full system (5 seeds)", "internal"),
    ("GPT-4.1-mini (stock)", "GPT-4.1-mini (stock)", "llm"),
    ("Llama-3.3-70B", "Llama-3.3-70B (DeepInfra)", "llm"),
    ("GBM, raw features", "GBM raw features", "method"),
    ("RF, raw features", "RF raw features", "method"),
    ("GPR, raw features", "GPR raw features", "method"),
    ("GPR, physics features", "GPR physics features", "method"),
]

T2_ARMS = [("ML-only", "ML-only"), ("ML + physics", "ML+physics"),
           ("ML + physics + KG", "ML+physics+KG"),
           ("Full system", "Full system (5 seeds)")]

STRATA = ("NEAR", "MID", "FAR")


def esc(s):
    """Escape the LaTeX specials that appear in these tables."""
    return (str(s).replace("\\", r"\textbackslash{}").replace("&", r"\&")
            .replace("%", r"\%").replace("_", r"\_").replace("#", r"\#"))


def header(name, source):
    return (f"% {name}\n"
            f"% Generated by evaluation/paper_assets/make_tables.py\n"
            f"% Source: {source}\n"
            f"% Do not edit by hand -- regenerate instead.\n")


def num(v, places=2, dash="--"):
    if v is None or (isinstance(v, float) and pd.isna(v)):
        return dash
    return f"{v:.{places}f}"


# ---------------------------------------------------------------- T1
def t1_main(out):
    h = pd.read_csv(os.path.join(RESULTS, "headline_metrics.csv"))

    def cell(arm, prop):
        r = h[(h.arm == arm) & (h.property == prop)]
        if r.empty:
            return "--", "--"
        r = r.iloc[0]
        mae = num(r["mae"], 2)
        if pd.notna(r.get("mae_sd")):
            mae = f"{mae} $\\pm$ {num(r['mae_sd'], 2)}"
        return mae, num(r["r2"], 3)

    # The common row set, not the per-property scored count: those differ
    # because not every row carries a measurement of every property.
    n_common = int(h.n_common_rows.iloc[0])
    per_prop = ", ".join(f"{p} $n={int(h[(h.property == p)].n_rows.iloc[0])}$"
                         for p, _ in PROPS)
    L = [header("T1: headline comparison",
                "evaluation/prediction/results/headline_metrics.csv"),
         r"\begin{table*}[t]", r"\centering",
         r"\caption{Prediction accuracy on the 88-alloy evaluation set. "
         r"Mean absolute error, with $R^2$ in parentheses. Lower MAE is better. "
         r"The agent system is stochastic and is reported as the mean $\pm$ "
         r"standard deviation over five seeds; every other arm is "
         r"deterministic and was run once.}",
         r"\label{tab:main}",
         r"\begin{tabular}{l" + "r" * len(PROPS) + "}", r"\toprule",
         "Method & " + " & ".join(f"{p} ({u})" for p, u in PROPS) + r" \\",
         r"\midrule"]
    group_seen = set()
    for label, key, group in T1_ARMS:
        if group not in group_seen and group_seen:
            L.append(r"\addlinespace")
        group_seen.add(group)
        cells = []
        for prop, _ in PROPS:
            mae, r2 = cell(key, prop)
            cells.append(f"{mae} ({r2})")
        L.append(f"{esc(label)} & " + " & ".join(cells) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}",
          r"\begin{minipage}{\textwidth}\vspace{2pt}\footnotesize",
          rf"All arms are scored on the identical set of {n_common} "
          r"(alloy, temperature) rows: every metric is computed only over rows "
          r"for which \emph{every} arm produced a prediction, so no method is "
          rf"evaluated on an easier subset than another. Rows scored per "
          rf"property ({per_prop}) differ only because not every row carries a "
          r"measurement of every property. Raw-feature baselines use element "
          r"weight percents and "
          r"test temperature alone; physics-feature arms add the engineered "
          r"metallurgical descriptors.",
          r"\end{minipage}", r"\end{table*}", ""]
    write(out, "T1_main.tex", L)


# ---------------------------------------------------------------- T2
def t2_stratified(out):
    s = pd.read_csv(os.path.join(RESULTS, "stratified_metrics.csv"))

    def cell(arm, prop, stratum):
        r = s[(s.method == arm) & (s.property == prop) & (s.stratum == stratum)]
        if r.empty or pd.isna(r.iloc[0]["mae"]):
            return "--"
        r = r.iloc[0]
        v = num(r["mae"], 2)
        if pd.notna(r.get("mae_sd")):
            v = f"{v} $\\pm$ {num(r['mae_sd'], 2)}"
        return v

    def n_of(prop, stratum):
        r = s[(s.property == prop) & (s.stratum == stratum)]
        return "--" if r.empty else str(int(r.iloc[0]["n_rows"]))

    L = [header("T2: per-stratum accuracy",
                "evaluation/prediction/results/stratified_metrics.csv"),
         r"\begin{table*}[t]", r"\centering",
         r"\caption{Mean absolute error by distance stratum. NEAR ($d < 2.0$) "
         r"are near-duplicates of training alloys under vendor naming, MID "
         r"($2.0 \le d < 4.5$) are distinct alloys within the knowledge-graph "
         r"anchoring cutoff, and FAR ($d \ge 4.5$) lie beyond it, where "
         r"anchoring cannot fire. $d$ is Euclidean distance on wt\%-normalised "
         r"composition to the nearest training alloy.}",
         r"\label{tab:stratified}",
         r"\begin{tabular}{ll" + "r" * len(T2_ARMS) + "}", r"\toprule",
         "Property & Stratum ($n$) & " + " & ".join(esc(l) for l, _ in T2_ARMS) + r" \\",
         r"\midrule"]
    for i, (prop, unit) in enumerate(PROPS):
        if i:
            L.append(r"\addlinespace")
        for j, st in enumerate(STRATA):
            first = f"{prop} ({unit})" if j == 0 else ""
            L.append(f"{first} & {st} ({n_of(prop, st)}) & "
                     + " & ".join(cell(key, prop, st) for _, key in T2_ARMS) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}",
          r"\begin{minipage}{\textwidth}\vspace{2pt}\footnotesize",
          r"ML-only and ML + physics are identical on yield strength by "
          r"construction: no enforcement rule touches it. ML + physics + KG is "
          r"identical to ML + physics on FAR by construction: no anchoring "
          r"proposal can be generated past the $d = 4.5$ cutoff. The full "
          r"system is a five-seed mean $\pm$ standard deviation.",
          r"\end{minipage}", r"\end{table*}", ""]
    write(out, "T2_stratified.tex", L)


# ---------------------------------------------------------------- T3
def t3_provenance(out):
    """Mechanism, where it helps, and the number that shows it.

    Values are pulled from the committed tables so the summary cannot drift
    from the detail tables it summarises.
    """
    s = pd.read_csv(os.path.join(RESULTS, "stratified_metrics.csv"))

    def mae(arm, prop, st):
        r = s[(s.method == arm) & (s.property == prop) & (s.stratum == st)]
        return None if r.empty else float(r.iloc[0]["mae"])

    def pct(a, b):
        return f"{100 * (b - a) / a:+.1f}\\%"

    kg_near = pct(mae("ML+physics", "YS", "NEAR"), mae("ML+physics+KG", "YS", "NEAR"))
    kg_mid = pct(mae("ML+physics", "YS", "MID"), mae("ML+physics+KG", "YS", "MID"))
    ag_far = pct(mae("ML+physics+KG", "YS", "FAR"), mae("Full system (5 seeds)", "YS", "FAR"))
    ag_all = pct(mae("ML+physics+KG", "YS", "ALL"), mae("Full system (5 seeds)", "YS", "ALL"))
    ph_all = pct(mae("ML-only", "EM", "ALL"), mae("ML+physics", "EM", "ALL"))
    ph_near = pct(mae("ML-only", "EM", "NEAR"), mae("ML+physics", "EM", "NEAR"))
    ph_mid = pct(mae("ML-only", "EM", "MID"), mae("ML+physics", "EM", "MID"))
    ag_em = pct(mae("ML+physics", "EM", "ALL"), mae("Full system (5 seeds)", "EM", "ALL"))

    rows = [
        ("Knowledge-graph anchoring",
         "Retrieves a stored measurement from a compositionally close alloy and "
         "blends it into the prediction",
         "Near-duplicates only",
         f"YS {kg_near} on NEAR, {kg_mid} on MID, exactly zero on FAR where the "
         f"$d = 4.5$ gate forbids it"),
        ("Deterministic physics",
         "Voigt--Reuss--Hill modulus, UTS/YS ceilings, elongation caps, applied "
         "after prediction",
         "Wherever the learned modulus is wrong, not where the system knows least",
         f"EM {ph_all} overall; {ph_near} on NEAR but {ph_mid} on MID, so the "
         f"gain is not monotonic in distance"),
        ("Agent layer",
         "Analyst and Reviewer reconcile ML, physics and retrieved evidence, and "
         "may revise a value",
         "All strata, most on the alloys furthest from training",
         f"YS {ag_far} on FAR and {ag_all} overall, unanimous across five seeds; "
         f"costs EM accuracy ({ag_em})"),
        ("Ontology and reasoner",
         "OWL class axioms and datatype range restrictions, checked by HermiT at "
         "ingestion",
         "Schema and interoperability; no effect on any prediction",
         "No runtime component loads the ontology. Zero range violations among "
         "the 77 curated alloys; the one real data defect encountered would have "
         "been caught by an existing bound, but sat in a record ingestion "
         "validation never sees"),
    ]
    L = [header("T3: mechanism provenance",
                "evaluation/prediction/results/stratified_metrics.csv "
                "(percentages), owl_reasoning_ablation.md (ontology row)"),
         r"\begin{table*}[t]", r"\centering",
         r"\caption{What each component contributes, where it contributes, and "
         r"the measurement that shows it. Percentages are changes in mean "
         r"absolute error against the arm immediately below the component in "
         r"the ablation ladder; negative is an improvement.}",
         r"\label{tab:provenance}",
         r"\begin{tabular}{@{}p{2.4cm}p{3.6cm}p{3.0cm}p{6.0cm}@{}}", r"\toprule",
         r"Component & Mechanism & Where it helps & Evidence \\", r"\midrule"]
    for i, (comp, mech, where, ev) in enumerate(rows):
        if i:
            L.append(r"\addlinespace")
        L.append(f"{esc(comp)} & {esc(mech)} & {esc(where)} & {ev} \\\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    write(out, "T3_provenance.tex", L)


# ---------------------------------------------------------------- T4
def t4_design(out):
    d = json.load(open(os.path.join(DESIGN, "random_search_baseline.json")))
    order = ["designer (LLM pipeline)",
             "random best-of-5", "random best-of-5 (plaus-aware)",
             "sparsity-matched best-of-5", "sparsity-matched best-of-5 (plaus-aware)",
             "random+Guard+Tuner best-of-5", "random+Guard+Tuner best-of-5 (plaus-aware)",
             "sparsity+Guard+Tuner best-of-5", "sparsity+Guard+Tuner best-of-5 (plaus-aware)",
             "random best-of-100", "random best-of-100 (plaus-aware)",
             "sparsity-matched best-of-100", "sparsity-matched best-of-100 (plaus-aware)"]
    by = {a["label"]: a for a in d["arms"]}
    pretty = {
        "designer (LLM pipeline)": ("LLM Designer", "5"),
        "random best-of-5": ("Random, uniform", "5"),
        "random best-of-5 (plaus-aware)": ("Random, uniform, plaus.\\ selection", "5"),
        "sparsity-matched best-of-5": ("Random, sparsity-matched", "5"),
        "sparsity-matched best-of-5 (plaus-aware)": ("Random, sparsity-matched, plaus.\\ selection", "5"),
        "random+Guard+Tuner best-of-5": ("Random, uniform + optimizer", "5"),
        "random+Guard+Tuner best-of-5 (plaus-aware)": ("Random, uniform + optimizer, plaus.\\ selection", "5"),
        "sparsity+Guard+Tuner best-of-5": ("Random, sparsity-matched + optimizer", "5"),
        "sparsity+Guard+Tuner best-of-5 (plaus-aware)": ("Random, sparsity-matched + optimizer, plaus.\\ selection", "5"),
        "random best-of-100": ("Random, uniform", "100"),
        "random best-of-100 (plaus-aware)": ("Random, uniform, plaus.\\ selection", "100"),
        "sparsity-matched best-of-100": ("Random, sparsity-matched", "100"),
        "sparsity-matched best-of-100 (plaus-aware)": ("Random, sparsity-matched, plaus.\\ selection", "100"),
    }
    L = [header("T4: inverse-design arms",
                "evaluation/design/results/random_search_baseline.json"),
         r"\begin{table*}[t]", r"\centering",
         r"\caption{Inverse design against 20 target specifications, all arms "
         r"scored by the same physics evaluator. \emph{Goals met} counts "
         r"individual property targets reached at 90\% of their value; "
         r"\emph{usable} requires every target met and TCP risk below Critical; "
         r"\emph{credible} additionally requires the composition to fall inside "
         r"the metallurgical plausibility envelope of the 77 reference alloys.}",
         r"\label{tab:design}",
         r"\begin{tabular}{@{}lrrrrr@{}}", r"\toprule",
         r"Arm & Cand. & Goals met & Usable & Credible & Median elem. \\",
         r"\midrule"]
    prev_budget = None
    for key in order:
        a = by.get(key)
        if not a:
            continue
        label, budget = pretty[key]
        if prev_budget is not None and budget != prev_budget:
            L.append(r"\addlinespace")
        prev_budget = budget
        n = a["n_designs"]
        L.append(f"{label} & {budget} & {a['hit_rate']:.1f}\\% & "
                 f"{a['usable']}/{n} & \\textbf{{{a['credible']}/{n}}} & "
                 f"{a['median_major_elements']} \\\\")
    L += [r"\bottomrule", r"\end{tabular}",
          r"\begin{minipage}{\textwidth}\vspace{2pt}\footnotesize",
          r"\emph{Median elem.} is the median number of deliberate additions "
          r"above 1\,wt\% and is the reason the uniform sampler fails: it draws "
          r"every element independently, producing 12.2 additions per candidate "
          r"in expectation against a plausibility cap of 8, so it fails the "
          r"element-count and trace-element rules before any search quality is "
          r"measured. The sparsity-matched sampler draws the element count, the "
          r"identities and the amounts from the empirical distribution of the 77 "
          r"reference alloys, and is the like-for-like comparison. All arms are "
          r"seeded and deterministic.",
          r"\end{minipage}", r"\end{table*}", ""]
    write(out, "T4_design.tex", L)


# ---------------------------------------------------------------- T5
def t5_conformal(out):
    c = pd.read_csv(os.path.join(RESULTS, "conformal_coverage.csv"))
    c["prop"] = c.property.str.upper()
    L = [header("T5: conformal coverage",
                "evaluation/prediction/results/conformal_coverage.csv"),
         r"\begin{table}[t]", r"\centering",
         r"\caption{Cross-conformal (CV+) prediction intervals at 90\% nominal "
         r"coverage, calibrated on out-of-fold residuals over the 77 training "
         r"alloys with folds grouped by alloy. Coverage is the fraction of "
         r"measured values falling inside the interval.}",
         r"\label{tab:conformal}",
         r"\begin{tabular}{@{}llrrr@{}}", r"\toprule",
         r"Property & Stratum & $n$ & Coverage & Median width \\", r"\midrule"]
    for i, (prop, unit) in enumerate(PROPS):
        if i:
            L.append(r"\addlinespace")
        sub = c[c.prop == prop]
        for j, st in enumerate(list(STRATA) + ["ALL"]):
            r = sub[sub.stratum == st]
            if r.empty:
                continue
            r = r.iloc[0]
            first = f"{prop} ({unit})" if j == 0 else ""
            name = r"\textbf{ALL}" if st == "ALL" else st
            cov = f"{100 * float(r['coverage']):.1f}\\%"
            if st == "ALL":
                cov = f"\\textbf{{{cov}}}"
            L.append(f"{first} & {name} & {int(r['n_scored'])} & {cov} & "
                     f"{num(float(r['median_width']), 1)} \\\\")
    L += [r"\bottomrule", r"\end{tabular}",
          r"\begin{minipage}{\linewidth}\vspace{2pt}\footnotesize",
          r"The CV+ guarantee is \emph{marginal}: it holds on average over an "
          r"exchangeable population, not within any subgroup, and the strata are "
          r"deliberately non-exchangeable with the training set. Per-stratum "
          r"figures are therefore diagnostic rather than guaranteed. Widths are "
          r"near-constant across strata by construction, since an "
          r"absolute-residual conformity score yields one quantile per property; "
          r"this is a property of the score, not evidence that distant alloys "
          r"are as predictable as near ones.",
          r"\end{minipage}", r"\end{table}", ""]
    write(out, "T5_conformal.tex", L)


def write(out, name, lines):
    path = os.path.join(out, name)
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"  {name:22s} {os.path.getsize(path):6d} bytes")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--outdir", default=DEFAULT_OUT)
    args = ap.parse_args()
    os.makedirs(args.outdir, exist_ok=True)
    t1_main(args.outdir)
    t2_stratified(args.outdir)
    t3_provenance(args.outdir)
    t4_design(args.outdir)
    t5_conformal(args.outdir)
    print(f"\nWritten to {args.outdir}")


if __name__ == "__main__":
    main()
